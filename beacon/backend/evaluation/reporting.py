"""BEACON V2 — Phase 4 Evaluation Reporting.

Generates audit-ready Markdown and structured JSON reports from EvaluationResult,
including complete traceability links, difference explanations, and cryptographic hashes.
"""

import json
from typing import Any

from .models import EvaluationResult, EvaluationVerdict


def generate_markdown_report(result: EvaluationResult) -> str:
    """Generates an audit-ready Markdown report for an EvaluationResult."""
    verdict_emoji = {
        EvaluationVerdict.EQUIVALENT: "✅ **EQUIVALENT**",
        EvaluationVerdict.DIFFERENT: "❌ **DIFFERENT**",
        EvaluationVerdict.INCONCLUSIVE: "⚠️ **INCONCLUSIVE**",
        EvaluationVerdict.ERROR: "💥 **ERROR**",
        EvaluationVerdict.NOT_APPLICABLE: "⚪ **NOT APPLICABLE**",
    }.get(result.verdict, str(result.verdict))

    lines = [
        "# BEACON Behavioral Equivalence Evaluation Report",
        "",
        f"**Overall Verdict:** {verdict_emoji}  ",
        f"**Application ID:** `{result.application_id}`  ",
        f"**Evaluation ID:** `{result.evaluation_id}`  ",
        f"**Bundle ID:** `{result.bundle_id}`  ",
        f"**Timestamp:** `{result.timestamp.isoformat()}`  ",
        f"**Comparison Policy:** `{result.policy_id}` (hash: `{result.policy_hash[:12]}...`)  ",
        f"**Coverage Ratio:** `{result.summary.coverage_ratio * 100:.1f}%`  ",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        "",
        f"- **Total Inputs Analyzed:** {result.summary.total_inputs}",
        f"- **Equivalent Inputs:** {result.summary.equivalent_inputs}",
        f"- **Different Inputs:** {result.summary.different_inputs}",
        f"- **Inconclusive Inputs:** {result.summary.inconclusive_inputs}",
        f"- **Total Behavioral Differences Detected:** {result.summary.total_differences}",
        "",
        "### Dimension Breakdown",
        "",
        "| Dimension | Evaluated | Equivalent | Different | Inconclusive | N/A | Verdict |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :--- |",
    ]

    for dim, dsum in result.summary.dimension_summaries.items():
        v_str = (
            "✅ Pass"
            if dsum.overall_verdict == EvaluationVerdict.EQUIVALENT
            else ("❌ Fail" if dsum.overall_verdict == EvaluationVerdict.DIFFERENT else str(dsum.overall_verdict.value))
        )
        lines.append(
            f"| **{dim.value.capitalize()}** | {dsum.total_evaluated} | {dsum.equivalent_count} | "
            f"{dsum.different_count} | {dsum.inconclusive_count} | {dsum.not_applicable_count} | {v_str} |"
        )

    lines.extend([
        "",
        "---",
        "",
        "## 2. Behavioral Differences Summary",
        "",
    ])

    if not result.differences:
        lines.append("*No behavioral differences detected between Reference and Target implementations.*")
    else:
        lines.extend([
            f"A total of **{len(result.differences)}** behavioral differences were recorded:",
            "",
            "| # | Input ID | Dimension | Difference Type | Field / Path | Reference Value | Target Value |",
            "| :-: | :--- | :--- | :--- | :--- | :--- | :--- |",
        ])
        for idx, diff in enumerate(result.differences, start=1):
            ref_val = str(diff.reference_value)
            if len(ref_val) > 40:
                ref_val = ref_val[:37] + "..."
            tgt_val = str(diff.target_value)
            if len(tgt_val) > 40:
                tgt_val = tgt_val[:37] + "..."

            field = diff.field_path or "-"
            lines.append(
                f"| {idx} | `{diff.input_id}` | `{diff.dimension.value}` | `{diff.difference_type.value}` | "
                f"`{field}` | `{ref_val}` | `{tgt_val}` |"
            )

    lines.extend([
        "",
        "---",
        "",
        "## 3. Cryptographic Verification & Audit Trail",
        "",
        f"- **Evaluation Hash:** `{result.evaluation_hash}`",
        f"- **Bundle Hash:** `{result.bundle_hash or 'N/A'}`",
        f"- **Policy Hash:** `{result.policy_hash}`",
        "",
        "*Report deterministically generated by BEACON V2 Phase 4 Engine.*",
    ])

    return "\n".join(lines)


def generate_json_report(result: EvaluationResult) -> dict[str, Any]:
    """Serializes EvaluationResult into an audit-ready dict."""
    return result.model_dump(mode="json")
